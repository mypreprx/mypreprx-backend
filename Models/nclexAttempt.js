import mongoose from 'mongoose';

const nclexAttemptSchema = new mongoose.Schema({
    userId: {
        type: mongoose.Schema.Types.ObjectId,
        ref: 'user',
        required: true
    },
    status: {
        type: String,
        enum: ['in-progress', 'pass', 'fail', 'abandoned'],
        default: 'in-progress'
    },
    decisionRule: {
        type: String,
        default: null
    },
    state: {
        theta: { type: Number, default: -0.25 },
        standard_error: { type: Number, default: 1.00 },
        total_items_answered: { type: Number, default: 0 },
        completed_case_studies: { type: Number, default: 0 },
        pretest_items_answered: { type: Number, default: 0 },
        elapsed_seconds: { type: Number, default: 0 },
        administered_item_ids: [{ type: String }],
        active_case_study_id: { type: String, default: null },
        case_study_items_delivered: { type: Number, default: 0 },
        active_case_study_data: { type: Object, default: null }
    },
    history: [{
        question: { type: Object }, // Store the full question generated by AI
        userAnswer: { type: mongoose.Schema.Types.Mixed }, // String or Array
        isCorrect: { type: Boolean },
        responseValue: { type: Number } // For partial credit (0.0 to 1.0)
    }]
}, { timestamps: true });

const nclexAttemptModel = mongoose.model('nclexAttempt', nclexAttemptSchema);
export default nclexAttemptModel;
